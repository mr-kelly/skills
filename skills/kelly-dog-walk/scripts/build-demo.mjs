#!/usr/bin/env node
/**
 * Build the AirApp's `?demo=1` dataset from the recorded Open-Meteo fixtures — never by hand.
 *
 *   node scripts/build-demo.mjs           # write content/kelly-dog-walk-app/app/demo-data.json
 *   node scripts/build-demo.mjs --check   # exit 1 if the committed file differs from a fresh build
 *
 * The story (references/story-2026-shanghai.json) says which playbook and judge were in force
 * each month; every number in the demo comes from replaying the real data through walk-model.js,
 * the same module the trusted scripts use. The decisions are stored in exactly the shape of the
 * 每天的决定 Base, so the demo renders through the same code path as a live Space.
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { decisionFields } from "../content/kelly-dog-walk-app/app/js/view-model.js";
import {
  daysFromMonthData,
  parseJudgeRules,
  parseRuleCard,
  replayMonth,
} from "../content/kelly-dog-walk-app/app/js/walk-model.js";
import { SKILL_ROOT, loadJudgeSource, loadPlaybookSource } from "./lib/cli.mjs";
import { PINNED_PLACES, loadMonth } from "./lib/open-meteo.mjs";

export const DEMO_FILE = path.join(SKILL_ROOT, "content", "kelly-dog-walk-app", "app", "demo-data.json");

export const buildDemo = async () => {
  const story = JSON.parse(await readFile(path.join(SKILL_ROOT, "references", "story-2026-shanghai.json"), "utf8"));
  const place = PINNED_PLACES[story.city];
  const judges = {};
  for (const version of new Set(story.months.map((month) => month.judge))) {
    judges[version] = parseJudgeRules((await loadJudgeSource(version, null)).content);
  }
  const baseline = parseRuleCard((await loadPlaybookSource("v1", null)).content);
  const decisions = [];
  const baselineWeather = {};
  for (const { month, playbook, judge } of story.months) {
    const days = daysFromMonthData(await loadMonth(place, month, { source: "fixtures" }));
    const card = parseRuleCard((await loadPlaybookSource(playbook, null)).content);
    for (const row of replayMonth(days, card, judges[judge], { city: place.name })) {
      decisions.push({ ...decisionFields(row), rule: row.rule });
    }
    for (const day of days) {
      const at = day.hours[baseline.defaultHour];
      baselineWeather[day.date] = { rain: at.rain, temp: at.temp };
    }
  }
  const last = story.months.at(-1);
  const strip = ({ text, ...judge }) => judge;
  return {
    format: "kelly-dog-walk/demo@1",
    note: "Generated by skills/kelly-dog-walk/scripts/build-demo.mjs from references/open-meteo/*.json. Do not edit by hand.",
    place: { name: place.name, latitude: place.latitude, longitude: place.longitude, timezone: place.timezone },
    baselineVersion: baseline.version,
    baselineHour: baseline.defaultHour,
    judgeByMonth: Object.fromEntries(story.months.map(({ month, judge }) => [month, judge])),
    judges: Object.fromEntries(Object.entries(judges).map(([version, judge]) => [version, strip(judge)])),
    currentJudge: last.judge,
    playbookMarkdown: (await loadPlaybookSource(last.playbook, null)).content,
    decisions,
    baselineWeather,
    closed: story.closed,
    judgeChanges: story.judgeChanges,
    en: story.en,
  };
};

const sameJson = (a, b) => JSON.stringify(a) === JSON.stringify(b);

if (import.meta.url === `file://${process.argv[1]}`) {
  const fresh = await buildDemo();
  if (process.argv.includes("--check")) {
    const current = JSON.parse(await readFile(DEMO_FILE, "utf8").catch(() => "null"));
    if (!sameJson(current, fresh)) {
      console.error("app/demo-data.json is stale. Run: node scripts/build-demo.mjs");
      process.exit(1);
    }
    console.log("app/demo-data.json is current.");
  } else {
    await writeFile(DEMO_FILE, `${JSON.stringify(fresh, null, 2)}\n`);
    console.log(`Wrote ${path.relative(process.cwd(), DEMO_FILE)} (${fresh.decisions.length} days).`);
  }
}
